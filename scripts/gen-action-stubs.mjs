#!/usr/bin/env node
// Writes the browser stubs for the server-function modules listed in src/features/rpc/modules.json, and the server registry.
//   node scripts/gen-action-stubs.mjs          write the files
//   node scripts/gen-action-stubs.mjs --check  exit 1 when they are out of date
// Each module `src/features/x/actions.ts` gets `actions.client.ts` next to it: one `rpc()` stub per exported function (typed
// like the original) plus its exported types. Client components import the stub; server code imports the module itself.
import fs from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const check = process.argv.includes('--check')
const modules = JSON.parse(fs.readFileSync(path.join(ROOT, 'src/features/rpc/modules.json'), 'utf8'))
const BANNER = '// GENERATED by scripts/gen-action-stubs.mjs. Do not edit by hand.\n'
let stale = 0

function write(file, text) {
  const full = path.join(ROOT, file)
  if (check) {
    if (!fs.existsSync(full) || fs.readFileSync(full, 'utf8') !== text) { console.error(`stale: ${file}`); stale++ }
  } else fs.writeFileSync(full, text)
}

function exportsOf(file) {
  const src = ts.createSourceFile(file, fs.readFileSync(path.join(ROOT, file), 'utf8'), ts.ScriptTarget.Latest, true)
  const fns = [], types = []
  for (const node of src.statements) {
    const mods = ts.canHaveModifiers(node) ? ts.getModifiers(node) ?? [] : []
    if (!mods.some((m) => m.kind === ts.SyntaxKind.ExportKeyword)) continue
    if (ts.isFunctionDeclaration(node) && node.name) fns.push(node.name.text)
    else if (ts.isVariableStatement(node)) for (const d of node.declarationList.declarations) if (ts.isIdentifier(d.name)) fns.push(d.name.text)
    else if (ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node)) types.push(node.name.text)
  }
  for (const node of src.statements) {
    if (ts.isTypeAliasDeclaration(node) || ts.isInterfaceDeclaration(node)) {
      const mods = ts.getModifiers(node) ?? []
      if (mods.some((m) => m.kind === ts.SyntaxKind.ExportKeyword) && !types.includes(node.name.text)) types.push(node.name.text)
    }
  }
  return { fns: [...new Set(fns)], types: [...new Set(types)] }
}

const registry = []
for (const mod of modules) {
  const file = `src/${mod}.ts`
  const base = path.basename(mod)
  const { fns, types } = exportsOf(file)
  let out = `${BANNER}import { rpc } from '@/features/rpc/client'\n\n`
  if (types.length) out += `export type { ${types.join(', ')} } from './${base}'\n\n`
  for (const fn of fns) out += `export const ${fn}: typeof import('./${base}').${fn} = rpc('${mod}', '${fn}') as never\n`
  write(`src/${mod}.client.ts`, out)
  registry.push(`  '${mod}': () => import('@/${mod}'),`)
}
write('src/features/rpc/registry.generated.ts', `${BANNER}export const RPC_MODULES: Record<string, () => Promise<Record<string, unknown>>> = {\n${registry.join('\n')}\n}\n`)
if (check && stale) process.exit(1)
console.log(check ? 'action stubs up to date' : `action stubs written for ${modules.length} modules`)
