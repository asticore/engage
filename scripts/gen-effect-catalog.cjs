/* eslint-disable @typescript-eslint/no-require-imports -- a CommonJS script, run by hand with node */
/**
 * Writes src/features/effects/catalogData.ts from the `.meta.js` files of a Spark checkout.
 *   node scripts/gen-effect-catalog.cjs <path to spark checkout> <commit it is pinned at>
 * Run it on the checkout pinned in reference/references.json, then commit the result.
 */
const fs = require('fs')
const path = require('path')

const root = path.resolve(process.argv[2] || '')
const commit = process.argv[3] || 'unknown'
if (!fs.existsSync(path.join(root, 'src'))) {
  console.error('Usage: node scripts/gen-effect-catalog.cjs <spark checkout> <commit>')
  process.exit(1)
}

const files = []
const walk = (dir) => {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name)
    if (entry.isDirectory()) walk(full)
    else if (entry.name.endsWith('.meta.js')) files.push(full)
  }
}
walk(path.join(root, 'src'))
files.sort()

const clean = (text) => String(text).replace(/\s+/g, ' ').trim()
const short = (text) => {
  const first = clean(text).split(/(?<=\.)\s/)[0]
  return first.length > 80 ? `${first.slice(0, 77)}...` : first
}

const effects = []
for (const file of files) {
  const meta = require(file)
  const cls = (meta.classes || []).map((c) => c[0]).find((c) => /^spark-[a-z0-9-]+$/.test(c))
  if (!cls) continue
  const options = []
  for (const [name, def, desc] of meta.options || []) {
    if (!/^data-spark-[a-z0-9-]+$/.test(name)) continue
    const attr = name.slice('data-spark-'.length)
    let type = 'text'
    let values
    if (def === 'true' || def === 'false') type = 'boolean'
    else if (/^-?\d+(\.\d+)?$/.test(def)) type = 'number'
    else {
      const tokens = clean(desc).replace(/\.$/, '').split(' · ')
      if (tokens.length > 1 && tokens.every((t) => /^[A-Za-z0-9_-]{1,24}$/.test(t))) {
        type = 'select'
        values = tokens
      }
    }
    const placeholder = def && !/^\(|^from /.test(def) && def !== '""' ? def : undefined
    options.push({ attr, label: short(desc), type, ...(values ? { values } : {}), ...(placeholder ? { placeholder } : {}) })
  }
  effects.push({ id: cls.slice('spark-'.length), label: clean(meta.title), group: clean(meta.group || 'Other'), className: cls, help: short(meta.summary || ''), options })
}

const out = `/* Generated by scripts/gen-effect-catalog.cjs from the Spark .meta.js files at commit ${commit}. Do not edit by hand. */
import type { EffectDef } from './catalog'

export const SPARK_CATALOG_COMMIT = ${JSON.stringify(commit)}

export const EFFECT_DATA: EffectDef[] = ${JSON.stringify(effects, null, 2).replace(/\u2014/g, '\\u2014')}
`
fs.writeFileSync(path.join(__dirname, '../src/features/effects/catalogData.ts'), out)
console.log(`${effects.length} effects`)
